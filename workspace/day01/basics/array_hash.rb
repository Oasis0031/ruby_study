# 배열과 해시

# 배열
# 배열은 여러 개의 값을 순서대로 저장할 수 있는 자료구조입니다. 배열은 대괄호 []를 사용하여 생성하며, 각 요소는 쉼표로 구분됩니다.

# arr = [1, 2, 3, 4, 5]
# arr.push(6) # 배열에 요소 추가
# arr.map { |x| x * 2 } # 배열의 각 요소를 2배로 만든 새로운 배열 반환
# arr.select { |x| x > 2 } # 배열에서 2보다 큰 요소만 선택하여 새로운 배열 반환
# arr.each { |x| puts x } # 배열의 각 요소를 출력
# arr.delete(3) # 배열에서 값이 3인 요소 삭제
# arr.include?(4) # 배열에 값이 4가 있는지 확인 (true/false)
# arr.size # 배열의 크기 반환
# arr.empty? # 배열이 비어있는지 확인 (true/false)
# arr.reverse # 배열을 뒤집은 새로운 배열 반환
# arr.sort # 배열을 오름차순으로 정렬한 새로운 배열 반환
# arr.uniq # 배열에서 중복된 요소를 제거한 새로운 배열 반환
# arr.join(", ") # 배열의 요소를 문자열로 합치기 (구분자는 ", ")
# arr.clear # 배열의 모든 요소 삭제
# arr.first # 배열의 첫 번째 요소 반환
# arr.last # 배열의 마지막 요소 반환
# arr.index(4) # 배열에서 값이 4인 요소의 인덱스 반환 (없으면 nil)
# arr.count(2) # 배열에서 값이 2인 요소의 개수 반환
# arr.sample # 배열에서 랜덤하게 하나의 요소 반환
# arr.rotate(2) # 배열을 2칸 회전시킨 새로운 배열 반환
# arr.zip([10, 20, 30]) # 두 배열을 병합하여 새로운 배열 반환
# arr.flatten # 다차원 배열을 1차원 배열로 평탄화
# arr.compact # 배열에서 nil 요소 제거한 새로운 배열 반환

# 해시
# 해시는 키-값 쌍으로 데이터를 저장하는 자료구조입니다. 해시는 중괄호 {}를 사용하여 생성하며, 
# 각 키와 값은 => 또는 :를 사용하여 연결됩니다.

hash = [{ name: "철수", age: 25 }, { name: "영희", age: 30 }]
  hash[0][:name] # 해시에서 값 가져오기
  hash.each do |person| # 해시의 각 키-값 쌍을 반복하면서 블록 실행
    puts "#{person[:name]}: #{person[:age]}"
end